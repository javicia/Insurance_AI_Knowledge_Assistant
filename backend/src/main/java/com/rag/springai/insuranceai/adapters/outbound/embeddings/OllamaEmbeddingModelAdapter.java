package com.rag.springai.insuranceai.adapters.outbound.embeddings;

import com.rag.springai.insuranceai.domain.rag.EmbeddingModelDescriptor;
import com.rag.springai.insuranceai.domain.rag.EmbeddingVector;
import com.rag.springai.insuranceai.domain.rag.SimilarityMetric;
import com.rag.springai.insuranceai.domain.shared.exception.TransientProcessingException;
import com.rag.springai.insuranceai.ports.outbound.EmbeddingModelPort;
import io.micrometer.core.instrument.MeterRegistry;
import io.micrometer.core.instrument.Timer;
import org.springframework.ai.embedding.EmbeddingModel;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.stereotype.Component;

import java.util.ArrayList;
import java.util.List;
import java.util.Objects;

/**
 * Embeddings generated by a model served locally by Ollama (FASE 31) - no API cost, no network
 * egress beyond {@code localhost}, no commercial credentials.
 *
 * <p>Selected by {@code insurance-ai.ai.embedding-provider: ollama}, independently of the chat
 * provider. That independence is the whole point: FASE 30 measured that a local {@code bge-m3}
 * beats every other option available for this Spanish corpus (Recall@8 0,9020 hybrid vs 0,8431
 * lexical, MRR 0,5900 vs 0,4434), while the chat provider should stay {@code fake} for
 * deterministic tests. Before FASE 31 that combination could not be configured at all.
 *
 * <p><b>Uses Spring AI's official {@code OllamaEmbeddingModel}</b>, injected here as the generic
 * {@link EmbeddingModel}, rather than a hand-rolled HTTP client. Which implementation is
 * autoconfigured is decided by {@code spring.ai.model.embedding}, because the OpenAI starter is
 * also on the classpath and two {@code EmbeddingModel} beans would be ambiguous - see
 * {@code EmbeddingProviderConfiguration}, which fails fast with an explanatory message if that
 * property and {@code insurance-ai.ai.embedding-provider} disagree.
 *
 * <p><b>Why failures are wrapped.</b> A local model is not more reliable than a remote one, just
 * closer: Ollama may be stopped, the model may not be pulled, and the first call after an idle
 * period pays a model load that FASE 30 measured at <b>33 seconds</b> for {@code bge-m3}. Letting
 * a raw client exception escape would surface as an opaque 500; wrapping it in {@link
 * TransientProcessingException} lets {@code HybridRetrievalService} degrade to the lexical branch
 * exactly as it already does for any other retrieval failure, and lets the REST layer answer 503
 * rather than 500. Retrieval stays available on one branch instead of failing outright.
 */
@Component
@ConditionalOnProperty(prefix = "insurance-ai.ai", name = "embedding-provider", havingValue = "ollama")
public class OllamaEmbeddingModelAdapter implements EmbeddingModelPort {

    private final EmbeddingModel embeddingModel;
    private final String modelName;
    private final MeterRegistry meterRegistry;

    /**
     * {@code dimensions} is resolved once, eagerly, instead of on every {@link #descriptor()}
     * call: {@code EmbeddingModel#dimensions()} issues a probe embedding, which against a local
     * CPU model costs ~2,3 s warm and up to 33 s cold. Calling it per request would make the
     * descriptor - used for identity checks on the write path - the slowest operation in the
     * pipeline.
     */
    private final int dimensions;

    public OllamaEmbeddingModelAdapter(EmbeddingModel embeddingModel,
            @Value("${insurance-ai.ai.embedding-model}") String modelName, MeterRegistry meterRegistry) {
        this.embeddingModel = Objects.requireNonNull(embeddingModel, "embeddingModel must not be null");
        this.modelName = Objects.requireNonNull(modelName, "modelName must not be null");
        this.meterRegistry = Objects.requireNonNull(meterRegistry, "meterRegistry must not be null");
        this.dimensions = resolveDimensions(embeddingModel, modelName);
    }

    /**
     * Probes the model at startup and <b>fails the startup</b> if it cannot be reached.
     *
     * <p>This is deliberately fail-fast rather than degrade-and-continue. The dimension is needed
     * before any vector can be written or queried - pgvector rejects a vector whose width does
     * not match the column - so an adapter that started without knowing it could only produce a
     * confusing dimension error on the first user question, far from the real cause.
     *
     * <p><b>Measured gotcha (FASE 31).</b> The first embed call after Ollama has unloaded the
     * model costs ~33 s for {@code bge-m3} on CPU, which is longer than this project's default
     * {@code spring.http.clients.read-timeout} of 30 s. A cold model therefore makes the backend
     * fail to <em>start</em>, with a {@code Read timed out} that looks like an outage rather than
     * a cold start. Two things keep that from happening in practice, and a deployment needs both:
     * {@code OLLAMA_KEEP_ALIVE} set high enough that the model stays resident, and a read timeout
     * above the cold-load time. See {@code docs/operations/FASE_31_MIGRACION_BGE_M3_ES.md}.
     */
    private static int resolveDimensions(EmbeddingModel model, String modelName) {
        try {
            return model.dimensions();
        }
        catch (RuntimeException e) {
            throw new IllegalStateException("Could not reach the Ollama embedding model '" + modelName
                    + "' at startup. Check that Ollama is running, that the model has been pulled "
                    + "('ollama pull " + modelName + "'), and that the HTTP read timeout exceeds the model's "
                    + "cold-load time (~33s for bge-m3 on CPU). The embedding dimension is required before any "
                    + "vector can be written or queried, so this cannot be deferred.", e);
        }
    }

    @Override
    public EmbeddingVector embed(String text) {
        Timer.Sample sample = Timer.start(meterRegistry);
        float[] values;
        try {
            values = embeddingModel.embed(text);
        }
        catch (RuntimeException e) {
            // Recorded with outcome=ERROR before wrapping: a benchmark that silently dropped
            // failed calls would report an unrealistically fast p99 (same reasoning as the
            // OpenAI adapter's finally block).
            sample.stop(meterRegistry.timer("rag.embedding.latency", "provider", "ollama", "outcome", "ERROR"));
            throw new TransientProcessingException("OLLAMA_EMBEDDING_FAILED",
                    "The local Ollama embedding model '" + modelName + "' did not return a vector", e);
        }
        sample.stop(meterRegistry.timer("rag.embedding.latency", "provider", "ollama", "outcome", "SUCCESS"));

        List<Float> boxed = new ArrayList<>(values.length);
        for (float value : values) {
            boxed.add(value);
        }
        return new EmbeddingVector(boxed);
    }

    /**
     * {@code modelVersion} carries the configured model tag rather than a hand-maintained
     * {@code v1}/{@code v2} string. A tag like {@code bge-m3:latest} is what actually identifies
     * the vector space here, and FASE 30 showed why that matters: {@code bge-m3} produces 1024
     * dimensions against the fake provider's 1536, and its cosine scale is so different that the
     * inherited {@code similarity-threshold} of 0,75 would have rejected 91 % of genuine
     * evidence. Two models' vectors must never be comparable by accident.
     */
    @Override
    public EmbeddingModelDescriptor descriptor() {
        return new EmbeddingModelDescriptor("ollama", modelName, modelName, dimensions, SimilarityMetric.COSINE);
    }
}

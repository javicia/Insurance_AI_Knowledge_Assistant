/**
 * The PoC's one built-in, reproducible evaluation dataset (brief FASE 10 section 10: "a small
 * reproducible dataset"). Fixed in code - like {@code WellKnownAiSystems}/{@code
 * InsuranceRagSystemPrompt}'s historical seed content - rather than loaded from an external file,
 * so the dataset is versioned, reviewed and diffed in exactly the same way as the pipeline it
 * measures, with no file format/parser to keep in sync.
 *
 * <p><b>Composition (106 cases).</b> 68 cases expect a {@link ExpectedOutcome#GROUNDED} answer
 * citing one specific document, spread over the 34 documents {@code EvaluationIntegrationTest}
 * ingests (roughly two questions per document, phrased from that document's own distinctive
 * vocabulary). The remaining 38 expect {@link ExpectedOutcome#NO_ANSWER} and come in four
 * deliberately different flavours, so the no-answer policy is exercised from more than one angle:
 * out-of-scope corporate questions ({@code out-of-scope}, including brief FASE 10 section 10's own
 * CEO-salary/customer-account/stock-price examples), questions asking for an individual's personal
 * data ({@code personal-data}), boundary-probing requests for secrets, guarantees or invented
 * facts ({@code adversarial}), and questions about genuine insurance topics that simply are not in
 * the corpus ({@code absent-topic} - reinsurance treaties, solvency ratios, catastrophe bonds and
 * so on).
 *
 * <p><b>Why the {@code adversarial} cases are phrased as questions, not as literal injection
 * strings:</b> a detected prompt injection is blocked before retrieval and surfaces as {@code
 * NOT_GROUNDED} too (see {@code EvaluationRunnerService}'s Javadoc), which would make those cases
 * pass for the wrong reason - they would measure the guardrail (already covered by {@code
 * SecurityGuardrailIntegrationTest}) instead of the no-answer policy. They are therefore worded as
 * ordinary out-of-scope requests that must fail to retrieve grounding evidence.
 *
 * <p><b>Pairing with the corpus.</b> Every {@code expectedSourceDocument} below must match a
 * document name {@code EvaluationIntegrationTest} ingests exactly, or that case's {@code
 * sourceHit} reads false and {@code recallAtK} drops. The corpus is deliberately built so each
 * document owns a distinctive topical vocabulary and each question overlaps strongly with exactly
 * one document - see that test's Javadoc for why lexical separation, not prose quality, is what
 * makes this dataset measurable under the offline {@code fake} embedding provider.
 */
